test('eight medals fill 2x4 and disable smaller layouts, with an internally scrolling editor',async({page},info)=>{
  await setup(page,8);await selectMedals(page)
  const button=(name:string)=>page.getByRole('button',{name,exact:true})
  await button('合并展览框').click()
  await expect(button('1 × 2 展览框')).toBeDisabled();await expect(button('1 × 4 展览框')).toBeDisabled()
  await button('2 × 4 展览框').click()
  await expect(page.locator('.scene .medal-exhibit-cell:not(.is-empty)')).toHaveCount(8)
  await expect(button('1 × 4 展览框')).toBeDisabled()
  await page.screenshot({path:info.outputPath('eight-medals.png')})
  await page.setViewportSize({width:390,height:640})
  expect(await page.locator('.record-scroll').evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
  await button('保存修改').click()
  await page.locator('.scene>.memory-exhibit').press('Enter')
  await page.getByRole('complementary',{name:'奖牌展览框编辑'}).getByRole('button',{name:'拆分展览框',exact:true}).click()
  await expect(page.locator('.scene>.memory-medal')).toHaveCount(8)
})
