import {test,expect} from '@playwright/test'
import type {Page} from '@playwright/test'

async function setup(page:Page,count=2){
  await page.addInitScript(({count})=>{
    if(sessionStorage.getItem('exhibit-fixture'))return
    localStorage.setItem('racememoir-board-v1',JSON.stringify({title:'奖牌展览',items:[
      ...Array.from({length:count},(_,index)=>({id:`m${index}`,kind:'medal',title:`赛事 ${index+1}`,variant:index%2?'silver':'bronze',x:200+(index%4)*240,y:200+Math.floor(index/4)*310,w:180,h:270,rotation:0})),
      {id:'note',kind:'note',title:'终点记忆',x:1300,y:220,w:160,h:160,rotation:0,variant:'paper'},
    ],threads:[{id:'t1',from:'m0',to:'note'},{id:'t2',from:'m1',to:'note'},{id:'t3',from:'m0',to:'m1'}]}))
    sessionStorage.setItem('exhibit-fixture','1')
  },{count})
  await page.goto('/');await page.locator('.records-loading').waitFor({state:'hidden'})
}
async function selectMedals(page:Page){
  const boxes=await page.locator('.scene>.memory-medal').evaluateAll(els=>els.map(el=>{const b=el.getBoundingClientRect();return {x:b.x,y:b.y,right:b.right,bottom:b.bottom}}))
  await page.keyboard.down('Control')
  await page.mouse.move(Math.min(...boxes.map(b=>b.x))-10,Math.min(...boxes.map(b=>b.y))-10)
  await page.mouse.down();await page.mouse.move(Math.max(...boxes.map(b=>b.right))+10,Math.max(...boxes.map(b=>b.bottom))+10,{steps:10});await page.mouse.up();await page.keyboard.up('Control')
  await expect(page.locator('.scene>.memory.selected')).toHaveCount(boxes.length)
}
const saved=(page:Page)=>page.evaluate(()=>JSON.parse(localStorage.getItem('racememoir-board-v1')||'{}'))

